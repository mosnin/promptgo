#!/usr/bin/env node
/**
 * Scans src/prompts/<slug>/meta.ts and writes one generated module.
 *
 * This exists so that many people can add prompt folders in parallel without
 * ever editing a shared barrel file, which removes the single biggest source of
 * merge conflicts in a fan out build.
 *
 * Unlike the tool directory this was adapted from, a prompt page has no bespoke
 * client component. The interactive part of every prompt page is the same
 * PromptPanel driven by `meta.prompt`, so a prompt is exactly one file and
 * there is no second artefact to keep in sync.
 *
 * Run via `npm run gen`, which is wired into both dev and build.
 */

import { readdir, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const promptsDir = path.join(root, "src", "prompts");
const outDir = path.join(root, "src", "generated");

/** Turn a kebab-case slug into a safe JS identifier. */
function identifier(slug) {
  return `p_${slug.replace(/[^a-z0-9]/gi, "_")}`;
}

async function main() {
  if (!existsSync(promptsDir)) {
    await mkdir(promptsDir, { recursive: true });
  }
  await mkdir(outDir, { recursive: true });

  const entries = await readdir(promptsDir, { withFileTypes: true });
  const slugs = [];
  const problems = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (existsSync(path.join(promptsDir, entry.name, "meta.ts"))) {
      slugs.push(entry.name);
    } else {
      problems.push(`  ${entry.name}: no meta.ts (skipped)`);
    }
  }

  slugs.sort();

  const imports = slugs
    .map((slug) => `import ${identifier(slug)} from "@/prompts/${slug}/meta";`)
    .join("\n");

  const list = slugs.map((slug) => `  ${identifier(slug)},`).join("\n");

  const file = `// AUTO GENERATED by scripts/generate-registry.mjs. Do not edit by hand.
// Add a prompt by creating src/prompts/<slug>/meta.ts then running \`npm run gen\`.
import type { PromptMeta } from "@/lib/types";

${imports}

export const promptMetas: PromptMeta[] = [
${list}
];

export const promptCount = ${slugs.length};
`;

  await writeFile(path.join(outDir, "prompt-metas.ts"), file, "utf8");

  console.log(`[gen] registered ${slugs.length} prompts`);
  if (problems.length) {
    console.warn(`[gen] incomplete prompt folders:\n${problems.join("\n")}`);
  }
}

main().catch((error) => {
  console.error("[gen] failed:", error);
  process.exit(1);
});
