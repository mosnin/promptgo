#!/usr/bin/env node
/**
 * Scans src/prompts/<slug>/meta.ts and src/tools/<slug>/{meta.ts,compute.ts}
 * and writes the generated modules both sides of the site import.
 *
 * This exists so that many people can add prompt or tool folders in parallel
 * without ever editing a shared barrel file, which removes the single biggest
 * source of merge conflicts in a fan out build.
 *
 * A prompt page has no bespoke client component: the interactive part of
 * every prompt page is the same PromptPanel driven by `meta.prompt`, so a
 * prompt is exactly one file. A tool is different, because its whole point is
 * computing something, so it is two files: `meta.ts` (content and form
 * fields, the same kind of data a prompt's meta.ts holds) and `compute.ts`
 * (the pure function that does the actual work). Keeping them separate means
 * the metadata can be scanned by the SEO auditor without evaluating logic,
 * and the logic can be run through a correctness test harness without a DOM.
 *
 * Run via `npm run gen`, which is wired into both dev and build.
 */

import { readdir, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const promptsDir = path.join(root, "src", "prompts");
const toolsDir = path.join(root, "src", "tools");
const skillsDir = path.join(root, "src", "skills");
const ideToolsDir = path.join(root, "src", "ide-tools");
const outDir = path.join(root, "src", "generated");

/** Turn a kebab-case slug into a safe JS identifier. */
function identifier(prefix, slug) {
  return `${prefix}_${slug.replace(/[^a-z0-9]/gi, "_")}`;
}

async function generatePrompts() {
  if (!existsSync(promptsDir)) {
    await mkdir(promptsDir, { recursive: true });
  }

  const entries = await readdir(promptsDir, { withFileTypes: true });
  const slugs = [];
  const problems = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (existsSync(path.join(promptsDir, entry.name, "meta.ts"))) {
      slugs.push(entry.name);
    } else {
      problems.push(`  ${entry.name}: no meta.ts (skipped)`);
    }
  }

  slugs.sort();

  const imports = slugs
    .map((slug) => `import ${identifier("p", slug)} from "@/prompts/${slug}/meta";`)
    .join("\n");

  const list = slugs.map((slug) => `  ${identifier("p", slug)},`).join("\n");

  const file = `// AUTO GENERATED by scripts/generate-registry.mjs. Do not edit by hand.
// Add a prompt by creating src/prompts/<slug>/meta.ts then running \`npm run gen\`.
import type { PromptMeta } from "@/lib/types";

${imports}

export const promptMetas: PromptMeta[] = [
${list}
];

export const promptCount = ${slugs.length};
`;

  await writeFile(path.join(outDir, "prompt-metas.ts"), file, "utf8");

  console.log(`[gen] registered ${slugs.length} prompts`);
  if (problems.length) {
    console.warn(`[gen] incomplete prompt folders:\n${problems.join("\n")}`);
  }
}

async function generateTools() {
  if (!existsSync(toolsDir)) {
    await mkdir(toolsDir, { recursive: true });
  }

  const entries = await readdir(toolsDir, { withFileTypes: true });
  const slugs = [];
  const problems = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const hasMeta = existsSync(path.join(toolsDir, entry.name, "meta.ts"));
    const hasCompute = existsSync(path.join(toolsDir, entry.name, "compute.ts"));
    if (hasMeta && hasCompute) {
      slugs.push(entry.name);
    } else {
      const missing = [!hasMeta && "meta.ts", !hasCompute && "compute.ts"].filter(Boolean).join(" and ");
      problems.push(`  ${entry.name}: missing ${missing} (skipped)`);
    }
  }

  slugs.sort();

  const metaImports = slugs
    .map((slug) => `import ${identifier("t", slug)} from "@/tools/${slug}/meta";`)
    .join("\n");
  const metaList = slugs.map((slug) => `  ${identifier("t", slug)},`).join("\n");

  const metaFile = `// AUTO GENERATED by scripts/generate-registry.mjs. Do not edit by hand.
// Add a tool by creating src/tools/<slug>/meta.ts and src/tools/<slug>/compute.ts,
// then running \`npm run gen\`.
import type { ToolMeta } from "@/lib/tool-types";

${metaImports}

export const toolMetas: ToolMeta[] = [
${metaList}
];

export const toolCount = ${slugs.length};
`;

  const computeImports = slugs
    .map((slug) => `import { compute as ${identifier("c", slug)} } from "@/tools/${slug}/compute";`)
    .join("\n");
  const computeEntries = slugs.map((slug) => `  "${slug}": ${identifier("c", slug)},`).join("\n");

  const computeFile = `// AUTO GENERATED by scripts/generate-registry.mjs. Do not edit by hand.
import type { ComputeFn } from "@/lib/tool-types";

${computeImports}

export const toolComputes: Record<string, ComputeFn> = {
${computeEntries}
};
`;

  await writeFile(path.join(outDir, "tool-metas.ts"), metaFile, "utf8");
  await writeFile(path.join(outDir, "tool-computes.ts"), computeFile, "utf8");

  console.log(`[gen] registered ${slugs.length} tools`);
  if (problems.length) {
    console.warn(`[gen] incomplete tool folders:\n${problems.join("\n")}`);
  }
}

